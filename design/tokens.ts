export const cssVar = (name: TokenName): string => `var(--tb-${name.replace(/[A-Z0-9]/g, c => '-' + c.toLowerCase())})`;

const toName = (k: string) => k.replace(/-([a-z0-9])/g, (_m, c: string) => c.toUpperCase()) as TokenName;
const resolveIn = (map: Record<string, string>, name: TokenName, seen: Set<string> = new Set()): string => {
  if (seen.has(name)) throw new Error(`token cycle at ${name}`);
  seen.add(name);
  const v = map[name];
  if (v === undefined) throw new Error(`unknown token ${name}`);
  return v.replace(/var\(--tb-([a-z0-9-]+)\)/g, (_, k: string) => resolveIn(map, toName(k), new Set(seen)));
};
const resolveAll = (map: Record<string, string>) => Object.fromEntries(Object.keys(tokens).map(k => [k, resolveIn(map, k as TokenName)])) as Record<TokenName, string>;

export const resolved = resolveAll({ ...tokens });
export const resolvedDark = resolveAll({ ...tokens, ...dark } as Record<string, string>);
